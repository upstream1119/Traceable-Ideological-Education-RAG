def focus_grade_evidence(query: str, hits: list[dict], entities: list[str]) -> list[dict]:
    # 仅对单主题问题使用标题锚点；综合/比较题不能据此丢弃另一主题的材料。
    if re.search(r"结合|综合|比较|对比|分别|联系|区别|以及|与|和", query):
        return hits
    anchors = [entity for entity in entities if len(entity) >= 3 and entity in query
               and any(entity in hit.get("title", "") for hit in hits)]
    if not anchors:
        return hits
    return [hit for hit in hits if any(entity in hit.get("title", "") for entity in anchors)]
